const AtomInfo& get_atom_info(const std::string& symbol) {
    std::string norm = symbol;

    if (!norm.empty()) {
        norm[0] = static_cast<char>(std::toupper(static_cast<unsigned char>(norm[0])));

        for (size_t i = 1; i < norm.size(); ++i) {
            norm[i] = static_cast<char>(std::tolower(static_cast<unsigned char>(norm[i])));
        }
    }

    auto it = ptable.find(norm);

    if (it != ptable.end()) {
        return it->second;
    }

    return default_atom;
}
