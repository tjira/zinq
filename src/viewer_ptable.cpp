/// Retrieves element properties by chemical symbol or atomic number with a fallback for unknown elements.
const AtomInfo& get_atom_info(const std::string& symbol) {
    std::string norm = symbol;

    if (!norm.empty()) {
        bool all_digits = true;

        for (char c : norm) {
            if (!std::isdigit(static_cast<unsigned char>(c))) {
                all_digits = false; break;
            }
        }

        if (all_digits) {
            try {
                int z = std::stoi(norm);

                auto it_num = kAtomicNumberToSymbol.find(z);

                if (it_num != kAtomicNumberToSymbol.end()) norm = it_num->second;
            } catch (...) {}
        }

        else {
            norm[0] = static_cast<char>(std::toupper(static_cast<unsigned char>(norm[0])));

            for (size_t i = 1; i < norm.size(); ++i) {
                norm[i] = static_cast<char>(std::tolower(static_cast<unsigned char>(norm[i])));
            }
        }
    }

    auto it = ptable.find(norm);

    if (it != ptable.end()) {
        return it->second;
    }

    return default_atom;
}
